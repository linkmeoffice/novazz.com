function renderHome() {
    const recent = novels.slice(0, 6);
    if (recent.length === 0) {
        homeContent.innerHTML = `
            <div class="empty-state">
                <div class="icon">📚</div>
                <h3>Belum ada novel</h3>
                <p>Silakan tambahkan novel terlebih dahulu.</p>
            </div>
        `;
        return;
    }

    let html = `<div class="section-title">Novel Terbaru <span class="count">(${novels.length})</span></div>`;
    html += `<div class="novel-grid">`;
    recent.forEach(n => {
        html += renderNovelCard(n);
    });
    html += `</div>`;
    homeContent.innerHTML = html;
}

function renderNovelCard(novel) {
    const coverHtml = novel.cover ?
        `<img src="${novel.cover}" alt="${novel.title}" loading="lazy" />` :
        `<div class="placeholder">${novel.title.charAt(0)}</div>`;

    const statusClass = novel.status === 'Completed' ? '' : '';

    return `
        <div class="novel-card" data-id="${novel.id}">
            <div class="cover">${coverHtml}</div>
            <div class="info">
                <div class="title">${novel.title}</div>
                <div class="author">${novel.author}</div>
                <div class="meta">
                    <span class="status">${novel.status}</span>
                    ${novel.genre.slice(0, 2).map(g => `<span class="genre-tag">${g}</span>`).join('')}
                </div>
                <div class="desc">${novel.synopsis.substring(0, 80)}${novel.synopsis.length > 80 ? '...' : ''}</div>
                <span class="btn-read">Baca</span>
            </div>
        </div>
    `;
}

function renderNovelList(genre, query) {
    const filtered = getFilteredNovels(genre, query);

    if (filtered.length === 0) {
        novelList.innerHTML = `
            <div class="empty-state">
                <div class="icon">🔍</div>
                <h3>Tidak ditemukan</h3>
                <p>Coba cari dengan kata kunci lain.</p>
            </div>
        `;
        return;
    }

    let html = `<div class="novel-grid">`;
    filtered.forEach(n => {
        html += renderNovelCard(n);
    });
    html += `</div>`;
    novelList.innerHTML = html;
}

function renderGenrePage(genre) {
    const filtered = getFilteredNovels(genre, '');
    const allGenres = getAllGenres();

    // Update filter chips
    let chipsHtml = `<button class="filter-chip ${genre === 'all' ? 'active' : ''}" data-genre="all">All</button>`;
    allGenres.forEach(g => {
        chipsHtml += `<button class="filter-chip ${genre === g ? 'active' : ''}" data-genre="${g}">${g}</button>`;
    });
    genreFilterBar.innerHTML = chipsHtml;

    if (filtered.length === 0) {
        genreList.innerHTML = `
            <div class="empty-state">
                <div class="icon">📭</div>
                <h3>Tidak ada novel di genre ini</h3>
            </div>
        `;
        return;
    }

    let html = `<div class="novel-grid">`;
    filtered.forEach(n => {
        html += renderNovelCard(n);
    });
    html += `</div>`;
    genreList.innerHTML = html;
}

