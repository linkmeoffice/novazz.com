function getNovel(id) {
    return novels.find(n => n.id === id);
}

function getAllGenres() {
    const set = new Set();
    novels.forEach(n => n.genre.forEach(g => set.add(g)));
    return Array.from(set).sort();
}

function getFilteredNovels(genre, query) {
    return novels.filter(n => {
        const matchGenre = genre === 'all' || n.genre.includes(genre);
        const matchQuery = query === '' || n.title.toLowerCase().includes(query.toLowerCase()) ||
            n.author.toLowerCase().includes(query.toLowerCase()) ||
            n.synopsis.toLowerCase().includes(query.toLowerCase());
        return matchGenre && matchQuery;
    });
}

function getReadingProgress(novelId) {
    return readingHistory[novelId] || 0;
}

function setReadingProgress(novelId, chapterIndex) {
    readingHistory[novelId] = chapterIndex;
    localStorage.setItem('readingHistory', JSON.stringify(readingHistory));
}

function loadReadingHistory() {
    try {
        const data = localStorage.getItem('readingHistory');
        if (data) readingHistory = JSON.parse(data);
    } catch (e) { /* ignore */ }
}

