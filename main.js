// Event delegation for novel cards (click to detail)
document.addEventListener('click', (e) => {
    const card = e.target.closest('.novel-card');
    if (card) {
        const id = card.dataset.id;
        if (id) {
            showPage('detail', id);
        }
        return;
    }

    // "Baca" button inside card
    const btn = e.target.closest('.btn-read');
    if (btn) {
        const card = btn.closest('.novel-card');
        if (card) {
            const id = card.dataset.id;
            if (id) {
                showPage('detail', id);
            }
        }
        return;
    }

    // Filter chips (novel page)
    const chip = e.target.closest('.filter-chip');
    if (chip && chip.closest('#filterBar')) {
        const genre = chip.dataset.genre;
        currentFilter = genre;
        $$('#filterBar .filter-chip').forEach(c => c.classList.toggle('active', c === chip));
        renderNovelList(genre, searchQuery);
        return;
    }

    // Filter chips (genre page)
    const genreChip = e.target.closest('.filter-chip');
    if (genreChip && genreChip.closest('#genreFilterBar')) {
        const genre = genreChip.dataset.genre;
        currentFilter = genre;
        renderGenrePage(genre);
        return;
    }

    // Chapter item in detail
    const chapterItem = e.target.closest('.chapter-item');
    if (chapterItem && chapterItem.closest('#detailContent')) {
        const index = parseInt(chapterItem.dataset.index);
        if (!isNaN(index) && currentNovelId) {
            showPage('reader', { novelId: currentNovelId, chapterIndex: index });
        }
        return;
    }

    // Start reading button
    const startBtn = e.target.closest('.btn-start');
    if (startBtn && startBtn.closest('#detailContent')) {
        const idx = parseInt(startBtn.dataset.chapter);
        if (!isNaN(idx) && currentNovelId) {
            showPage('reader', { novelId: currentNovelId, chapterIndex: idx });
        }
        return;
    }

    // Reader back button
    if (e.target.closest('#readerBack')) {
        if (currentNovelId) {
            showPage('detail', currentNovelId);
        } else {
            showPage('home');
        }
        return;
    }

    // Reader prev/next
    const prevBtn = e.target.closest('#readerPrev');
    if (prevBtn) {
        if (currentNovelId && currentChapterIndex > 0) {
            showPage('reader', { novelId: currentNovelId, chapterIndex: currentChapterIndex - 1 });
        }
        return;
    }

    const nextBtn = e.target.closest('#readerNext');
    if (nextBtn) {
        const novel = getNovel(currentNovelId);
        if (novel && currentChapterIndex < novel.chapters.length - 1) {
            showPage('reader', { novelId: currentNovelId, chapterIndex: currentChapterIndex + 1 });
        }
        return;
    }

    // Font size controls
    const fontDec = e.target.closest('#fontDec');
    if (fontDec) {
        fontSize = Math.max(12, fontSize - 1);
        updateReaderFont();
        return;
    }

    const fontInc = e.target.closest('#fontInc');
    if (fontInc) {
        fontSize = Math.min(28, fontSize + 1);
        updateReaderFont();
        return;
    }

    // Width toggle
    const widthToggleBtn = e.target.closest('#widthToggle');
    if (widthToggleBtn) {
        isWide = !isWide;
        updateReaderWidth();
        widthToggleBtn.textContent = isWide ? '⊞' : '⊟';
        return;
    }
});

function updateReaderFont() {
    const body = document.getElementById('readerContentBody');
    if (body) {
        body.style.fontSize = fontSize + 'px';
    }
    const display = document.getElementById('fontDisplay');
    if (display) {
        display.textContent = fontSize;
    }
}

function updateReaderWidth() {
    const body = document.getElementById('readerContentBody');
    if (body) {
        body.style.maxWidth = isWide ? '100%' : 'var(--reader-width)';
    }
}

