function showPage(page, data) {
    // Hide all pages
    Object.keys(pages).forEach(key => {
        pages[key].classList.remove('active');
    });

    // Update nav links
    $$('.nav-links a').forEach(link => {
        link.classList.toggle('active', link.dataset.page === page);
    });

    currentPage = page;

    // Show target page
    switch (page) {
        case 'home':
            pages.home.classList.add('active');
            renderHome();
            break;
        case 'novel':
            pages.novel.classList.add('active');
            renderNovelList(currentFilter, searchQuery);
            break;
        case 'genre':
            pages.genre.classList.add('active');
            renderGenrePage(currentFilter);
            break;
        case 'about':
            pages.about.classList.add('active');
            break;
        case 'detail':
            pages.detail.classList.add('active');
            if (data) {
                currentNovelId = data;
                renderDetail(data);
            }
            break;
        case 'reader':
            pages.reader.classList.add('active');
            if (data && data.novelId !== undefined && data.chapterIndex !== undefined) {
                currentNovelId = data.novelId;
                currentChapterIndex = data.chapterIndex;
                renderReader(data.novelId, data.chapterIndex);
            }
            break;
        default:
            pages.home.classList.add('active');
            renderHome();
    }

    // Close mobile menu
    navLinks.classList.remove('open');
    navSearch.classList.remove('open');

    // Scroll to top
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

